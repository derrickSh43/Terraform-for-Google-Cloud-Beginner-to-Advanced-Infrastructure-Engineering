"""Thin wrapper around the terraform binary.

Everything runs with:
  * a shared plugin cache, so the Terraform Registry is hit once per machine;
  * a fake OAuth token and real credentials stripped from the environment, so a
    plan can never touch a real Google Cloud project;
  * a backend override, so `backend "gcs"` blocks plan against local state.
"""

from __future__ import annotations

import os
import re
import shutil
import stat
import subprocess
from dataclasses import dataclass
from pathlib import Path

from . import paths

FAKE_TOKEN = "offline-course-token-not-a-real-credential"
DEFAULT_PROJECT = "meridian-course-sandbox"

# Inherited settings that could reach a real Google Cloud project or change how Terraform behaves
# (credentials, impersonation, TF_CLI_ARGS*, TF_CLI_CONFIG_FILE, TF_VAR_*...). Compared upper-cased:
# Windows environment names are case-insensitive, and Python reports them upper-case.
_STRIP_PREFIXES = ("TF_", "GOOGLE_", "CLOUDSDK_", "GCLOUD_")

# The only providers a course check may install. Anything else (external, http, local, ...) could run
# programs or reach the network during a plan, so init refuses it.
ALLOWED_PROVIDERS = ("registry.terraform.io/hashicorp/google", "registry.terraform.io/hashicorp/random")
CLI_CONFIG = paths.STATE_DIR / "terraform.rc"

OVERRIDE_NAME = "zz_course_backend_override.tf"
OVERRIDE_BODY = """# Generated by the course checker. Forces local state so that plans run offline.
terraform {
  backend "local" {
    path = "course.tfstate"
  }
}
"""

_COPY_SUFFIXES = (".tf", ".tfvars", ".tftpl", ".tpl", ".sh", ".json", ".yaml", ".yml", ".txt", ".hcl", ".ps1", ".py", ".md", ".html")
_SKIP_DIRS = {".terraform", ".git", "__pycache__"}
_SKIP_FILES = {"terraform.tfstate", "terraform.tfstate.backup", "course.tfstate"}


@dataclass
class Result:
    code: int
    stdout: str
    stderr: str

    @property
    def ok(self) -> bool:
        return self.code == 0

    @property
    def output(self) -> str:
        return (self.stdout + ("\n" + self.stderr if self.stderr else "")).strip()


def binary() -> str | None:
    return shutil.which("terraform")


def version() -> tuple[int, int, int] | None:
    exe = binary()
    if not exe:
        return None
    out = subprocess.run([exe, "version", "-json"], capture_output=True, text=True).stdout
    m = re.search(r'"terraform_version"\s*:\s*"(\d+)\.(\d+)\.(\d+)', out)
    return tuple(int(x) for x in m.groups()) if m else None  # type: ignore[return-value]


def _cli_config() -> Path:
    providers = ", ".join(f'"{p}"' for p in ALLOWED_PROVIDERS)
    text = (
        "# Generated by the course checker: only the course's providers can be installed.\n"
        "provider_installation {\n"
        f'  filesystem_mirror {{\n    path    = "{paths.PLUGIN_CACHE.as_posix()}"\n    include = [{providers}]\n  }}\n'
        f"  direct {{\n    include = [{providers}]\n  }}\n"
        "}\n"
    )
    paths.STATE_DIR.mkdir(parents=True, exist_ok=True)
    if not CLI_CONFIG.is_file() or CLI_CONFIG.read_text(encoding="utf-8") != text:
        CLI_CONFIG.write_text(text, encoding="utf-8")
    return CLI_CONFIG


def env() -> dict[str, str]:
    e = {k: v for k, v in os.environ.items() if not k.upper().startswith(_STRIP_PREFIXES)}
    paths.PLUGIN_CACHE.mkdir(parents=True, exist_ok=True)
    e.update(
        {
            "TF_CLI_CONFIG_FILE": str(_cli_config()),
            "TF_PLUGIN_CACHE_DIR": str(paths.PLUGIN_CACHE),
            "TF_PLUGIN_CACHE_MAY_BREAK_DEPENDENCY_LOCK_FILE": "1",
            "TF_IN_AUTOMATION": "1",
            "TF_INPUT": "0",
            "CHECKPOINT_DISABLE": "1",
            "GOOGLE_OAUTH_ACCESS_TOKEN": FAKE_TOKEN,
            "GOOGLE_PROJECT": os.environ.get("COURSE_DEFAULT_PROJECT", DEFAULT_PROJECT),
        }
    )
    return e


def _is_junction(p: Path) -> bool:
    try:
        return getattr(p.lstat(), "st_reparse_tag", 0) == getattr(stat, "IO_REPARSE_TAG_MOUNT_POINT", -1)
    except OSError:
        return False


def _locked(lock: Path) -> set[tuple[str, str]]:
    """{("registry.terraform.io/hashicorp/google", "8.12.0")} from a dependency lock file."""
    text = lock.read_text(encoding="utf-8", errors="replace") if lock.is_file() else ""
    return set(re.findall(r'(?m)^provider "([^"]+)" \{\s*version\s*=\s*"([^"]+)"', text))


def link_providers(cwd: Path) -> None:
    """Windows, before init: give a build folder junctions to the cached providers its lock file names.

    Terraform links providers from the cache, but on Windows that needs symlink rights most people
    don't have, so it copies 115 MB into every build folder instead. Junctions need no rights.
    Only locked versions are linked: init verifies those and leaves them alone. Anything else it may
    (re)install, and an install must never write through a link into the cache other checks are using.
    """
    if os.name != "nt" or paths.BUILD not in cwd.resolve().parents:
        return
    try:
        import _winapi

        top = cwd / ".terraform" / "providers"
        if _is_junction(top):               # made by an older version of this function
            os.rmdir(top)
        locked = _locked(cwd / ".terraform.lock.hcl")
        for pkg in paths.PLUGIN_CACHE.glob("*/*/*/*/*"):           # host/namespace/type/version/os_arch
            rel = pkg.relative_to(paths.PLUGIN_CACHE)
            link = top / rel
            if ("/".join(rel.parts[:3]), rel.parts[3]) not in locked:
                if _is_junction(link):
                    os.rmdir(link)          # removes the link, not the cached provider
                continue
            if _is_junction(link):
                continue
            if link.is_dir():
                shutil.rmtree(link)         # a copy made before the junction existed
            link.parent.mkdir(parents=True, exist_ok=True)
            _winapi.CreateJunction(str(pkg), str(link))
    except OSError:                         # e.g. an exFAT drive: Terraform copies, as before
        pass


def run(args: list[str], cwd: Path, timeout: int = 600) -> Result:
    exe = binary()
    if not exe:
        raise SystemExit("terraform was not found on PATH. Run `python course.py setup` for help.")
    if args[0] == "init":
        link_providers(cwd)
    proc = subprocess.run(
        [exe, *args],
        cwd=cwd,
        env=env(),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=timeout,
    )
    return Result(proc.returncode, proc.stdout, proc.stderr)


def sync_build_dir(
    src: Path,
    build: Path,
    extra: Path | None = None,
    roots: list[str] | None = None,
    states: dict[str, Path] | None = None,
) -> None:
    """Mirror the student's files into a private build directory.

    `roots` are the Terraform root modules inside the tree ("" = the top).
    Each root gets the backend override and (if missing) the shared lock file;
    `states` maps a root to a prepared state file copied in as its local state.
    `.terraform/` dirs and lock files in the build tree survive between runs so
    init stays fast. `extra` (lesson tests) is copied into <first root>/tests.
    """
    roots = roots or [""]
    build.mkdir(parents=True, exist_ok=True)
    wanted: dict[Path, Path | bytes] = {}                # build path -> source file, or its contents
    for f in _walk(src, _SKIP_DIRS):
        if f.name not in _SKIP_FILES and (f.suffix in _COPY_SUFFIXES or f.name == ".terraform.lock.hcl"):
            wanted[build / f.relative_to(src)] = f
    for root in roots:
        rdir = build / root
        rdir.mkdir(parents=True, exist_ok=True)
        if not (src / root / ".terraform.lock.hcl").exists() and paths.SHARED_LOCK.exists():
            wanted[rdir / ".terraform.lock.hcl"] = paths.SHARED_LOCK
        wanted[rdir / OVERRIDE_NAME] = OVERRIDE_BODY.encode()
        if states and root in states and states[root].exists():
            wanted[rdir / "course.tfstate"] = states[root]
    if extra and extra.is_dir():
        for f in extra.glob("*.tftest.hcl"):
            wanted[build / roots[0] / "tests" / f.name] = f

    for f in _walk(build, {".terraform"}):
        if f not in wanted and f.name != ".terraform.lock.hcl":
            f.unlink()
    for dirpath, dirs, _ in os.walk(build, topdown=False):
        d = Path(dirpath)
        if ".terraform" not in d.relative_to(build).parts and d != build and not any(d.iterdir()):
            d.rmdir()
    for dest, source in wanted.items():
        data = source if isinstance(source, bytes) else source.read_bytes()
        if not dest.is_file() or dest.read_bytes() != data:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(data)
    for root in roots:
        (build / root).mkdir(parents=True, exist_ok=True)


def _walk(top: Path, skip: set[str]):
    """Every file under `top`, without entering directories named in `skip`."""
    for dirpath, dirs, files in os.walk(top):
        dirs[:] = [d for d in dirs if d not in skip]
        for name in files:
            yield Path(dirpath) / name


def tf_files(src: Path) -> list[Path]:
    return [p for p in src.rglob("*.tf") if ".terraform" not in p.parts]
